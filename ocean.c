static void
ocn_depth(void)
{
    double dz[] = {
        2.0,    3.0,    4.0,    4.0,    5.0,
        5.0,    6.0,    6.0,    7.0,    8.0,
        8.0,    8.0,    8.0,    8.0,    10.0,
        10.0,   12.0,   12.0,   14.0,   14.0,
        16.0,   18.0,   20.0,   24.0,   28.0,
        30.0,   35.0,   40.0,   45.0,   50.0,
        50.0,   50.0,   50.0,   50.0,   50.0,
        60.0,   70.0,   70.0,   80.0,   80.0,
        100.0,  120.0,  120.0,  140.0,  160.0,
        180.0,  200.0,  200.0,  200.0,  200.0,
        250.0,  250.0,  250.0,  250.0,  250.0,
        250.0,  350.0,  400.0,  500.0,  500.0,
        600.0,  660.0,  100.0,
    };
    double zbnds[64];
    double z0[64];
    size_t k;
    GT3_Dim *axes[4];

    assert(sizeof dz / sizeof(double) == 63);

    zbnds[0] = 0.;
    for (k = 1; k < 64; ++k)
        zbnds[k] = zbnds[k - 1] + dz[k - 1];

    z0[0] = 0.; /* extra grid */
    for (k = 1; k < 64; ++k)
        z0[k] = 0.5 * (zbnds[k - 1] + zbnds[k]);

    /* `zlev` in ocean_sigma_z */
    for (k = 1; k < 64; ++k) {
        z0[k] *= -1.;
        zbnds[k] *= -1.;
    }
    axes[0] = new_GT3_Dim(63, "OCDEPT63",   "ocean level", "m", z0 + 1);
    axes[1] = new_GT3_Dim(64, "OCDEPT63.M", "ocean level", "m", zbnds);
    axes[2] = new_GT3_Dim(63, "OCDEPM63",   "ocean level", "m", zbnds);
    axes[3] = new_GT3_Dim(64, "OCDEPM63.M", "ocean level", "m", z0);

    write_axes(axes, 4);
    for (k = 0; k < 4; ++k) {
        GT3_freeDim(axes[k]);
    }
}


void
make_med52(void)
{
    ocn_depth();
    ocn_lon(360);
    ocn_lat_med52();
}
