#define MAX_LENGTH 4000


static void
ocn_lon(int len)
{
    const char *title = "longitude";
    const char *units = "degrees";
    const double global_deg = 360.0;
    double dx = global_deg / len;
    char name[4][17];
    double lonv[MAX_LENGTH + 2];
    double lont[MAX_LENGTH + 2];
    GT3_Dim *axes[4];
    int i;

    assert(len > 0);
    assert(len <= MAX_LENGTH);

    for (i = 0; i < len + 2; ++i) {
        lonv[i] = i * dx;
        lont[i] = (i + 0.5) * dx;
    }

    sprintf(name[0], "OCLONTPT%d",   len);
    sprintf(name[1], "OCLONTPV%d",   len);
    sprintf(name[2], "OCLONTPT%d.M", len);
    sprintf(name[3], "OCLONTPV%d.M", len);

    /* grids */
    axes[0] = new_GT3_Dim(len + 1, name[0], title, units, lont);
    axes[1] = new_GT3_Dim(len + 1, name[1], title, units, lonv + 1);

    /* bounds */
    axes[2] = new_GT3_Dim(len + 2, name[2], title, units, lonv);
    axes[3] = new_GT3_Dim(len + 2, name[3], title, units, lont);

    for (i = 0; i < 4; ++i) {
        axes[i]->cyclic = 1;
    }

    write_axes(axes, 4);
    for (i = 0; i < 4; ++i) {
        GT3_freeDim(axes[i]);
    }
}


